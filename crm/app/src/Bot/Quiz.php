<?php

declare(strict_types=1);

namespace App\Bot;

/**
 * Квиз «Подходит ли вам банкротство» — копия src/data/quiz.ts сайта (вопросы, расчёт, строка для заявки).
 * Меняете квиз на сайте — поменяйте и здесь, чтобы бот и сайт отвечали одинаково.
 */
final class Quiz
{
    /** @var list<array{name: string, q: string, hint: string, options: list<array{0: string, 1: string}>}> */
    public const QUESTIONS = [
        [
            'name' => 'debt',
            'q' => 'Какая общая сумма долгов?',
            'hint' => 'Кредиты, карты, микрозаймы, налоги, ЖКХ, долги по распискам — всё вместе',
            'options' => [['lt25', 'меньше 25 000 ₽'], ['25-500', 'от 25 000 до 500 000 ₽'], ['500-1m', 'от 500 000 до 1 000 000 ₽'], ['gt1m', 'больше 1 000 000 ₽']],
        ],
        [
            'name' => 'fssp',
            'q' => 'Приставы окончили исполнительное производство, потому что взыскать нечего?',
            'hint' => 'Это постановление об окончании по п. 4 ч. 1 ст. 46 закона об исполнительном производстве. Его видно на Госуслугах',
            'options' => [['yes', 'да, окончили'], ['no', 'нет, идёт или его нет'], ['unknown', 'не знаю']],
        ],
        [
            'name' => 'property',
            'q' => 'Есть ли имущество кроме единственного жилья и вещей?',
            'hint' => 'Автомобиль, вторая квартира, доля, гараж, земельный участок, доля в ООО',
            'options' => [['no', 'нет'], ['yes', 'да, есть']],
        ],
