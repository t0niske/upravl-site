            'name' => 'mortgage',
            'q' => 'Единственное жильё в ипотеке?',
            'hint' => 'Ипотечная квартира не защищена от продажи, даже если она единственная',
            'options' => [['no', 'нет'], ['yes', 'да, в ипотеке'], ['nohome', 'своего жилья нет']],
