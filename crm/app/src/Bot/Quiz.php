            'hint' => 'Включая сделки с родственниками, раздел имущества с супругом, отказ от наследства',
            'options' => [['no', 'нет'], ['yes', 'да']],
        ],
        [
            'name' => 'income',
            'q' => 'Есть официальный доход, которого хватило бы погасить долги за 3 года?',
            'hint' => 'Если да, суд может ввести реструктуризацию: долги платят по графику без пеней',
            'options' => [['no', 'нет, не хватит'], ['yes', 'да, хватит']],
        ],
    ];

    public static function count(): int
    {
        return count(self::QUESTIONS);
    }

    public static function label(int $step, string $value): ?string
    {
        foreach (self::QUESTIONS[$step]['options'] ?? [] as [$v, $label]) {
            if ($v === $value) {
                return $label;
            }
        }

        return null;
    }

    /**
     * @param array<string, string> $a
     * @return array{title: string, text: string, notes: list<string>, link: ?array{0: string, 1: string}}
     */
    public static function decide(array $a): array
    {
        $notes = [];

        if (($a['debt'] ?? '') === 'lt25') {
            return [
                'title' => 'Банкротство вам, скорее всего, не нужно',
                'text' => 'При долге до 25 000 ₽ процедура банкротства обойдётся дороже самого долга. Обычно такие вопросы решаются переговорами с кредитором, отсрочкой или оспариванием начислений',
                'notes' => $notes,
                'link' => null,
            ];
        }

        $title = 'Вам подходит судебное банкротство';
        $text = 'Дело рассматривает Арбитражный суд Томской области, процедуру ведёт финансовый управляющий. Итог для большинства должников — освобождение от долгов';

        if (($a['income'] ?? '') === 'yes') {
            $title = 'Возможна реструктуризация или списание долгов';
            $text = 'При достаточном доходе суд может утвердить план реструктуризации: долги платятся по графику до 3 лет, без пеней и штрафов. Если дохода не хватает, вводится реализация имущества и долги списываются';
        }

        if (in_array($a['debt'] ?? '', ['gt1m', '500-1m'], true)) {
            $notes[] = 'При долге от 500 000 ₽ и невозможности платить подать заявление — не только право, но и обязанность гражданина (30 рабочих дней)';
        }
        if (($a['property'] ?? '') === 'yes') {
            $notes[] = 'Имущество сверх защищённого законом (единственное жильё, вещи обихода) продают на торгах. Разберём, что сохранится, ещё до подачи';
        }
        if (($a['mortgage'] ?? '') === 'yes') {
            $notes[] = 'Ипотечная квартира не защищена статусом единственного жилья. Варианты: реструктуризация, мировое соглашение, продолжение платежей по договору с согласия банка';
        }
        if (($a['deals'] ?? '') === 'yes') {
            $notes[] = 'Сделки за 3 года до подачи могут оспорить. Нужен анализ до заявления — это главный риск процедуры';
        }
        $notes[] = 'Обязательные расходы: 25 000 ₽ на депозит суда для вознаграждения финансового управляющего и публикации';

        return ['title' => $title, 'text' => $text, 'notes' => $notes, 'link' => ['/bankrotstvo-fizicheskih-lic/', 'Как проходит банкротство граждан']];
    }

    /** Строка для поля «Ответы теста» в заявке — как на сайте. */
    public static function summary(array $a): string
    {
        $debt = ['lt25' => 'долг < 25 тыс.', '25-500' => 'долг 25–500 тыс.', '500-1m' => 'долг 0,5–1 млн', 'gt1m' => 'долг > 1 млн'];
        $ru = static fn (?string $v): string => ['yes' => 'да', 'no' => 'нет', 'unknown' => 'не знает', 'nohome' => 'нет жилья'][$v ?? ''] ?? (string) $v;

        return 'Квиз (бот): ' . self::decide($a)['title'] . '; ' . ($debt[$a['debt'] ?? ''] ?? '')
            . '; ИП окончено приставами: ' . $ru($a['fssp'] ?? null)
            . '; имущество: ' . $ru($a['property'] ?? null)
            . '; ипотека: ' . $ru($a['mortgage'] ?? null)
            . '; сделки за 3 года: ' . $ru($a['deals'] ?? null)
            . '; доход на 3 года: ' . $ru($a['income'] ?? null);
    }
}
