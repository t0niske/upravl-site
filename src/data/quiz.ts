export interface QuizResult {
  title: string;
  text: string;
  notes: string[];
  link: null | [string, string];
}

export function decide(a: A): QuizResult {
  const notes: string[] = [];
  if (a.debt === 'lt25') {
    return {
      title: 'Банкротство вам, скорее всего, не нужно',
      text: 'При долге до 25 000 ₽ процедура банкротства обойдётся дороже самого долга. Обычно такие вопросы решаются переговорами с кредитором, отсрочкой или оспариванием начислений',
      notes,
      link: null,
    };
  }
  let title = 'Вам подходит судебное банкротство';
  let text = 'Дело рассматривает Арбитражный суд Томской области, процедуру ведёт финансовый управляющий. Итог для большинства должников — освобождение от долгов';
  if (a.income === 'yes') {
    title = 'Возможна реструктуризация или списание долгов';
    text = 'При достаточном доходе суд может утвердить план реструктуризации: долги платятся по графику до 3 лет, без пеней и штрафов. Если дохода не хватает, вводится реализация имущества и долги списываются';
  }
  if (a.debt === 'gt1m' || a.debt === '500-1m') notes.push('При долге от 500 000 ₽ и невозможности платить подать заявление — не только право, но и обязанность гражданина (30 рабочих дней)');
  if (a.property === 'yes') notes.push('Имущество сверх защищённого законом (единственное жильё, вещи обихода) продают на торгах. Разберём, что сохранится, ещё до подачи');
  if (a.mortgage === 'yes') notes.push('Ипотечная квартира не защищена статусом единственного жилья. Варианты: реструктуризация, мировое соглашение, продолжение платежей по договору с согласия банка');
  if (a.deals === 'yes') notes.push('Сделки за 3 года до подачи могут оспорить. Нужен анализ до заявления — это главный риск процедуры');
  notes.push('Обязательные расходы: 25 000 ₽ на депозит суда для вознаграждения финансового управляющего и публикации');
  return { title, text, notes, link: ['/bankrotstvo-fizicheskih-lic/', 'Как проходит банкротство граждан'] };
}

const DEBT: Record<string, string> = {
  lt25: 'долг < 25 тыс.', '25-500': 'долг 25–500 тыс.', '500-1m': 'долг 0,5–1 млн', gt1m: 'долг > 1 млн',
};
const ru = (v: string) => ({ yes: 'да', no: 'нет', unknown: 'не знает', nohome: 'нет жилья' } as Record<string, string>)[v] ?? v;

/** Строка для скрытого поля заявки */
export function summary(a: A, title: string) {
  return `Квиз: ${title}; ${DEBT[a.debt] ?? ''}; ИП окончено приставами: ${ru(a.fssp)}; имущество: ${ru(a.property)}; ипотека: ${ru(a.mortgage)}; сделки за 3 года: ${ru(a.deals)}; доход на 3 года: ${ru(a.income)}`;
}
