const COURT: [string, string] = ['/bankrotstvo-fizicheskih-lic/', 'Как проходит судебное банкротство'];

export function decideMfc(a: A): QuizResult {
  const notes: string[] = [];
  if (a.debt === 'lt25') {
    return {
      title: 'Банкротство вам, скорее всего, не нужно',
      text: 'При долге меньше 25 000 ₽ внесудебное банкротство недоступно, а судебная процедура обойдётся дороже самого долга. Обычно такие вопросы решаются переговорами с кредитором или отсрочкой',
      notes,
      link: null,
    };
  }
  if (a.debt === 'gt1m') {
    notes.push('Через суд списывают долг любой суммы. Единственное жильё без ипотеки сохраняют');
    return {
      title: 'Через МФЦ не получится: долг больше 1 000 000 ₽',
      text: 'Внесудебное банкротство доступно при общей сумме долгов от 25 000 до 1 000 000 ₽. При большей сумме нужна судебная процедура',
      notes,
      link: COURT,
    };
  }
  if (a.prev === 'yes') {
    return {
      title: 'Через МФЦ пока нельзя',
      text: 'Повторно обратиться в МФЦ можно не раньше чем через 5 лет после прошлого банкротства. Разберём, какой путь остаётся',
      notes,
      link: null,
    };
  }
  if (a.fssp === 'unknown') {
    notes.push('Постановление можно получить на Госуслугах или у пристава');
    if (a.property === 'yes') notes.push('Если есть имущество, которое можно продать, кредиторы вправе перевести дело в суд');
    return {
      title: 'Нужно проверить постановление пристава',
      text: 'Главное условие МФЦ — производство окончено по п. 4 ч. 1 ст. 46, то есть взыскать нечего. Посмотрю постановление на бесплатной консультации и скажу, подходит ли МФЦ',
      notes,
      link: null,
    };
  }
  if (a.fssp === 'no') {
    notes.push('Если приставы окончат производство из-за отсутствия имущества, откроется бесплатный путь через МФЦ. Иногда имеет смысл подождать');
    notes.push('Если ждать нельзя, подойдёт судебное банкротство');
    return {
      title: 'Пока МФЦ, скорее всего, не подходит',
      text: 'Основной путь в МФЦ — производство, оконченное потому, что взыскать нечего. Есть и другие основания: для пенсионеров, получателей пособия на ребёнка и при долге, не взысканном 7 лет. Проверю, подходит ли одно из них',
      notes,
      link: COURT,
    };
  }
  if (a.newip === 'yes') {
    return {
      title: 'МФЦ вернёт заявление',
      text: 'Если после окончания производства возбудили новое и оно не окончено, внесудебное банкротство недоступно. Разберём, когда оно закончится или подойдёт ли судебная процедура',
      notes,
      link: COURT,
    };
  }
  if (a.property === 'yes') {
    notes.push('В суде имущество сверх защищённого законом продают на торгах. Разберём, что сохранится, ещё до подачи');
    return {
      title: 'Через МФЦ рискованно: есть имущество',
      text: 'Если есть имущество, которое можно продать, кредиторы вправе перевести дело в суд. Скорее подойдёт судебное банкротство',
      notes,
      link: COURT,
    };
  }
  notes.push('Процедура бесплатная, длится 6 месяцев, суд и финансовый управляющий не нужны');
  notes.push('Важно правильно составить список кредиторов: долги, которые не указаны в заявлении, не спишут');
  if (a.newip === 'unknown') notes.push('Перед подачей проверьте на Госуслугах, что новых открытых производств нет');
  if (a.deals === 'yes') notes.push('Сделки за 3 года стоит обсудить до подачи: если дело перейдёт в суд, кредитор может их оспорить');
  return {
    title: 'Похоже, вам подходит банкротство через МФЦ',
    text: 'Сумма долга в пределах 25 000–1 000 000 ₽, производство окончено, имущества нет — это базовые условия внесудебного банкротства',
    notes,
    link: null,
  };
}

const ru = (v: string) => ({ yes: 'да', no: 'нет', unknown: 'не знает' } as Record<string, string>)[v] ?? v;
const DEBT: Record<string, string> = { lt25: 'долг < 25 тыс.', '25-1m': 'долг 25 тыс. – 1 млн', gt1m: 'долг > 1 млн' };

/** Строка для скрытого поля заявки */
export function summaryMfc(a: A, title: string) {
  return `Квиз МФЦ: ${title}; ${DEBT[a.debt] ?? ''}; ИП окончено приставами: ${ru(a.fssp)}; новое ИП: ${ru(a.newip)}; имущество: ${ru(a.property)}; сделки за 3 года: ${ru(a.deals)}; банкротство за 5 лет: ${ru(a.prev)}`;
}
